"""Export the approved root logo as white offline LCD/web assets (Pillow 13.0.0).

Run from any directory with: python tools/render_header_logo.py
The canonical transparent artwork's alpha preserves the merged mark exactly.
"""

import base64
import hashlib
from io import BytesIO
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]


def render(source):
    image = Image.open(source).convert("RGBA")
    alpha = image.getchannel("A")
    bounds = alpha.getbbox()
    if bounds is None:
        raise ValueError("Logo is empty")
    alpha = alpha.crop(bounds)
    lcd = alpha.resize(
        (round(alpha.width * 16 / alpha.height), 16), Image.Resampling.LANCZOS
    )
    web_alpha = alpha.resize(
        (round(alpha.width * 64 / alpha.height), 64), Image.Resampling.LANCZOS
    )
    web = Image.new("RGBA", web_alpha.size, (255, 255, 255, 0))
    web.putalpha(web_alpha)
    png = BytesIO()
    web.save(png, format="PNG", optimize=True)
    lines = [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/render_header_logo.py from MyPi-transparent.png.",
        f"// Source SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}",
        f"// Alpha crop (left, top, right, bottom): {bounds}",
        f"#define HEADER_LOGO_W {lcd.width}",
        f"#define HEADER_LOGO_H {lcd.height}",
        "#ifdef HEADER_LOGO_LCD",
        "static const uint8_t s_header_logo[] = {",
    ]
    pixels = list(lcd.get_flattened_data())
    for start in range(0, len(pixels), lcd.width):
        lines.append("    " + ", ".join(str(p) for p in pixels[start:start + lcd.width]) + ",")
    lines.extend([
        "};",
        "#endif",
        "",
        '#define HEADER_LOGO_URI "data:image/png;base64,'
        + base64.b64encode(png.getvalue()).decode("ascii") + '"',
    ])
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "main" / "header_logo.h").write_text(render(ROOT / "MyPi-transparent.png"))
