"""Generate the LCD's antialiased title from DejaVu Sans Bold (Pillow 13.0.0).

Run with the path to DejaVuSans-Bold.ttf; no font files or rasterizer are needed
on the device. Only header lettering is affected, not the home screen's fields.
"""

import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("font", type=Path)
args = parser.parse_args()
font = ImageFont.truetype(str(args.font), 16 * 4)
bounds = font.getbbox("Hotspot")
image = Image.new("L", (bounds[2] - bounds[0], bounds[3] - bounds[1]))
ImageDraw.Draw(image).text((-bounds[0], -bounds[1]), "Hotspot", font=font, fill=255)
image = image.resize(
    (round(image.width / 4), round(image.height / 4)), Image.Resampling.LANCZOS
)
assert image.height <= 16
pixels = list(image.get_flattened_data())
lines = [
    "#pragma once",
    "",
    "#include <stdint.h>",
    "",
    "// Generated by tools/render_header_font.py; see assets/DejaVu-LICENSE.txt.",
    f"// Font SHA256: {hashlib.sha256(args.font.read_bytes()).hexdigest()}",
    f"#define HEADER_TITLE_W {image.width}",
    f"#define HEADER_TITLE_H {image.height}",
    "static const uint8_t s_header_title[] = {",
]
for start in range(0, len(pixels), image.width):
    lines.append("    " + ", ".join(str(p) for p in pixels[start:start + image.width]) + ",")
lines.append("};")
output = Path(__file__).resolve().parents[1] / "main" / "header_font.h"
output.write_text("\n".join(lines) + "\n")
